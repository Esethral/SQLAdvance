def alert_scan(text):

    if not text:
        return []

    keywords = db.session.query(Keyword).all()

    matches = []

    for kw in keywords:
        if re.search(rf"\b{re.escape(kw.keyword)}\b", text, re.IGNORECASE):
            matches.append(kw.keyword)

    if matches:

        subject = "EMERGENCY KEYWORD ALERT"

        body = (
            f"Detected Keywords: {', '.join(matches)}\n\n"
            "Entry Text:\n"
            "----------------------------------------\n"
            f"{text}\n"
            "----------------------------------------\n\n"
            "Email Generated by SQLAdvance"
        )

        alert_send(
            subject=subject,
            body=body
        )

        internal_users = (
            db.session.query(EmailInternal)
            .filter(EmailInternal.alert == "Yes")
            .all()
        )

        if not internal_users:
            return None

        for user in internal_users:
            send_message(
                receiver_id=user.user_id,
                receiver_name=user.fullname,
                subject=subject,
                body=body,
                sender="Keyword Scanner"
            )

    return matches

def alert_send(subject, body):

    recipients = [
        r.user_email
        for r in db.session.query(EmailNotification)
        .filter(EmailNotification.alert == "Yes")
        .all()
    ]

    if not recipients:
        return None

    cmd = [
        "mutt",
        "-s", subject,
        "-c", ",".join(recipients),
        "--",
        recipients[0],
    ]

    return subprocess.run(cmd, input=body, text=True, capture_output=True)

def check_session_timeout():
    timeout_threshold = 240  # minutes

    username = session.get("username")
    if not username:
        return

    login_row = (
        db.session.query(Login)
        .filter(Login.username == username)
        .order_by(Login.logtime.desc())
        .first()
    )

    if not login_row or not login_row.logtime:
        return

    # --- normalize BOTH sides to UTC-aware ---
    current_time = datetime.now(timezone.utc)

    login_time = login_row.logtime

    # if DB returns naive datetime, assume UTC
    if login_time.tzinfo is None:
        login_time = login_time.replace(tzinfo=timezone.utc)

    # if DB returns aware datetime, normalize to UTC
    else:
        login_time = login_time.astimezone(timezone.utc)

    diff_minutes = (current_time - login_time).total_seconds() / 60

    if diff_minutes > timeout_threshold:
        logout_user()
        session.clear()

