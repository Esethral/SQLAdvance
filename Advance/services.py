def send_message(
        receiver_id,
        receiver_name,
        subject,
        body,
        sender="System",
        sender_id=0):

    note = Message(
        sender=sender,
        sender_id=sender_id,
        receiver=receiver_name,
        receiver_id=receiver_id,
        subject=subject,
        body=body
    )

    db.session.add(note)
    db.session.commit()

    return note

